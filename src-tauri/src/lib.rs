type LabState<'a> = State<'a, Arc<Lab>>;

#[tauri::command]
#[specta::specta]
fn lab_snapshot(lab: LabState<'_>) -> Snapshot {
    lab.snapshot()
}

/// Writes one property and returns the read-back. Runs off the main thread.
#[tauri::command]
#[specta::specta]
async fn lab_write(lab: LabState<'_>, code: u16, value: Value) -> Result<WriteOutcome, String> {
    let lab = lab.inner().clone();
    tauri::async_runtime::spawn_blocking(move || lab.write(code, value)).await.map_err(|e| e.to_string())
}

#[tauri::command]
#[specta::specta]
fn lab_pin(lab: LabState<'_>, codes: Vec<u16>) {
    lab.pin(codes)
}

#[tauri::command]
#[specta::specta]
fn lab_keep_awake(lab: LabState<'_>, on: bool) {
    lab.keep_awake(on)
}

#[tauri::command]
#[specta::specta]
fn lab_connect(lab: LabState<'_>, on: bool) {
    lab.connect(on)
}

#[tauri::command]
#[specta::specta]
async fn lab_export(lab: LabState<'_>) -> Result<String, String> {
    let lab = lab.inner().clone();
    tauri::async_runtime::spawn_blocking(move || lab.export()).await.map_err(|e| e.to_string())?
}

#[tauri::command]
#[specta::specta]
fn lab_label(lab: LabState<'_>, patch: LabelPatch) -> Result<Catalog, String> {
    lab.label(patch)
}

#[tauri::command]
#[specta::specta]
fn lab_note(lab: LabState<'_>, group: Option<u32>, text: String) {
    lab.note(group, text)
}

#[tauri::command]
#[specta::specta]
fn lab_fake(lab: LabState<'_>, action: FakeAction) -> Result<(), String> {
    lab.fake(action)
}

/// Parses pasted recipe text into slot settings, notes and per-field warnings.
#[tauri::command]
#[specta::specta]
fn recipe_parse(text: String) -> recipes::Parsed {
    recipes::parse_text(&text)
}

pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new()
        .commands(tauri_specta::collect_commands![
            lab_snapshot,
            lab_write,
            lab_pin,
            lab_keep_awake,
            lab_connect,
            lab_export,
            lab_label,
            lab_note,
            lab_fake,
            recipe_parse,
        ])
        // The bundled recipe catalogue's shape; the window imports the JSON itself.
        .typ::<recipes::catalogue::RecipeCatalog>()
        .events(tauri_specta::collect_events![lab::LabStatus, lab::LabProps, lab::LabChanges, lab::CatalogChanged])
        // Wall-clock ms and codes fit a JS number.
        .dangerously_cast_bigints_to_number()
}

pub fn bindings_language() -> specta_typescript::Typescript {
    specta_typescript::Typescript::default()
        .header("// Generated by tauri-specta from src-tauri/src/lib.rs (ukiyo_lib::specta_builder).\n// Do not edit. Regenerate: UKIYO_UPDATE_BINDINGS=1 cargo test bindings\n")
}

/// The data folder name before the bundle ID became `com.nkmkdigital.ukiyo`.
const OLD_DATA_DIR: &str = "app.ukiyo";

/// Moves the old data folder (a sibling of `data_dir` named [`OLD_DATA_DIR`]) to `data_dir`,
/// once: only when the old one exists and the new one does not. Returns the old path if it moved.
fn migrate_data_dir(data_dir: &std::path::Path) -> std::io::Result<Option<std::path::PathBuf>> {
    let Some(parent) = data_dir.parent() else { return Ok(None) };
    let old = parent.join(OLD_DATA_DIR);
    if old == data_dir || !old.is_dir() || data_dir.exists() {
        return Ok(None);
    }
    std::fs::rename(&old, data_dir)?;
    Ok(Some(old))
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let specta = specta_builder();
    #[cfg(debug_assertions)]
    {
        let out = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../app/src/bindings.ts");
        if let Err(e) = specta.export(bindings_language(), &out) {
            eprintln!("ukiyo: bindings.ts not written: {e}");
        }
    }
    let typed = specta.invoke_handler();
    let app = tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .invoke_handler(typed)
        .setup(move |app| {
            specta.mount_events(app);
            let data_dir = app.path().app_data_dir()?;
            match migrate_data_dir(&data_dir) {
                Ok(Some(old)) => eprintln!("ukiyo: moved {} to {}", old.display(), data_dir.display()),
                Ok(None) => {}
                Err(e) => eprintln!("ukiyo: old data folder not moved: {e}"),
            }
            std::fs::create_dir_all(&data_dir)?;
            let catalog_dir = lab::catalog_dir(&data_dir, app.path().resource_dir().ok());
            let handle = app.handle().clone();
            let lab = Lab::start(data_dir, catalog_dir, move |e| {
                let _ = match e {
                    LabEvent::Status(x) => x.emit(&handle),
                    LabEvent::Props(x) => x.emit(&handle),
                    LabEvent::Changes(x) => x.emit(&handle),
                    LabEvent::Catalog(x) => x.emit(&handle),
                };
            });
            app.manage(lab);
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("ukiyo starts");
    app.run(|handle, event| {
        if let tauri::RunEvent::ExitRequested { .. } = event {
            if let Some(lab) = handle.try_state::<Arc<Lab>>() {
                lab.shutdown();
            }
        }
    });
}

#[cfg(test)]
mod tests {
    #[test]
    fn bindings() {
        let dir = tempfile::tempdir().unwrap();
        let out = dir.path().join("bindings.ts");
        super::specta_builder().export(super::bindings_language(), &out).unwrap();
        let fresh = std::fs::read_to_string(out).unwrap();
        let committed = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../app/src/bindings.ts");
        if std::env::var_os("UKIYO_UPDATE_BINDINGS").is_some() {
            std::fs::write(&committed, &fresh).unwrap();
            return;
        }
        let on_disk = std::fs::read_to_string(&committed).unwrap_or_default();
        assert!(on_disk == fresh, "app/src/bindings.ts is out of date: UKIYO_UPDATE_BINDINGS=1 cargo test bindings");
    }

    #[test]
    fn migrate_data_dir_moves_old_folder_once() {
        let root = tempfile::tempdir().unwrap();
        let old = root.path().join(super::OLD_DATA_DIR);
        let new = root.path().join("com.nkmkdigital.ukiyo");

        // Nothing to move.
        assert_eq!(super::migrate_data_dir(&new).unwrap(), None);

        std::fs::create_dir_all(old.join("sessions")).unwrap();
        std::fs::write(old.join("settings.json"), "{}").unwrap();
        assert_eq!(super::migrate_data_dir(&new).unwrap(), Some(old.clone()));
        assert!(!old.exists());
        assert_eq!(std::fs::read_to_string(new.join("settings.json")).unwrap(), "{}");
        assert!(new.join("sessions").is_dir());

        // The new folder wins: an old one that reappears stays where it is.
        std::fs::create_dir_all(&old).unwrap();
        assert_eq!(super::migrate_data_dir(&new).unwrap(), None);
        assert!(old.exists());
    }

    /// The hosts of every https `url` and `homepage` in the bundled recipe catalogue.
    fn catalogue_link_hosts(root: &std::path::Path) -> std::collections::BTreeSet<String> {
        fn walk(v: &serde_json::Value, out: &mut std::collections::BTreeSet<String>) {
            match v {
                serde_json::Value::Object(m) => {
                    for (k, v) in m {
                        if let (true, Some(u)) = (k == "url" || k == "homepage", v.as_str()) {
                            if let Some(host) = https_host(u) {
                                out.insert(host);
                            }
                        }
                        walk(v, out);
                    }
                }
                serde_json::Value::Array(a) => a.iter().for_each(|v| walk(v, out)),
                _ => {}
            }
        }
        let dir = root.join("catalog/recipes");
        let mut files = vec![dir.join("catalog.json")];
        files.extend(std::fs::read_dir(dir.join("sources")).unwrap().map(|e| e.unwrap().path()));
        let mut out = std::collections::BTreeSet::new();
        for f in files.iter().filter(|f| f.extension().is_some_and(|x| x == "json")) {
            let v: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(f).unwrap()).unwrap();
            walk(&v, &mut out);
        }
        out
    }

    /// The host of an https URL, or None when the URL is not https or the host is malformed.
    fn https_host(u: &str) -> Option<String> {
        let rest = u.strip_prefix("https://")?;
        let host = rest.split(['/', '?', '#']).next()?.to_ascii_lowercase();
        let ok = host.contains('.') && host.chars().all(|c| c.is_ascii_alphanumeric() || c == '.' || c == '-');
        ok.then_some(host)
    }

    /// `capabilities/links.json` lets the window open https links on the catalogue's hosts only.
    #[test]
    fn link_hosts() {
        let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
        let allow: Vec<_> = catalogue_link_hosts(&manifest.join(".."))
            .into_iter()
            .map(|h| serde_json::json!({ "url": format!("https://{h}/*") }))
            .collect();
        let cap = serde_json::json!({
            "$schema": "../gen/schemas/desktop-schema.json",
            "identifier": "links",
            "description": "Open recipe links in the default browser: https on the recipe catalogue's hosts only. Generated: UKIYO_UPDATE_LINK_HOSTS=1 cargo test link_hosts",
            "windows": ["main"],
            "permissions": [{ "identifier": "opener:allow-open-url", "allow": allow }]
        });
        let fresh = serde_json::to_string_pretty(&cap).unwrap() + "\n";
        let committed = manifest.join("capabilities/links.json");
        if std::env::var_os("UKIYO_UPDATE_LINK_HOSTS").is_some() {
            std::fs::write(&committed, &fresh).unwrap();
            return;
        }
        let on_disk = std::fs::read_to_string(&committed).unwrap_or_default();
        assert!(on_disk == fresh, "capabilities/links.json is out of date: UKIYO_UPDATE_LINK_HOSTS=1 cargo test link_hosts");
    }

    #[test]
    fn https_host_rejects_http_and_malformed() {
        assert_eq!(https_host("https://Film.Recipes/2024/x/?a#b").as_deref(), Some("film.recipes"));
        assert_eq!(https_host("http://fujixweekly.com/"), None);
        assert_eq!(https_host("https://fujixweekly-com/2019/"), None);
        assert_eq!(https_host("https://a.com@evil.com/"), None);
    }
}
