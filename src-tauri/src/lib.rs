use camera::owner::WriteOutcome;
use camera::ptp::Value;
use catalog::{Catalog, LabelPatch};
use lab::{FakeAction, Lab, LabEvent, Snapshot};
use std::sync::Arc;
use tauri::{Manager, State};
use tauri_specta::Event as _;

type LabState<'a> = State<'a, Arc<Lab>>;

#[tauri::command]
#[specta::specta]
fn lab_snapshot(lab: LabState<'_>) -> Snapshot {
    lab.snapshot()
}

/// Writes one property and returns the read-back. Runs off the main thread.
#[tauri::command]
#[specta::specta]
async fn lab_write(lab: LabState<'_>, code: u16, value: Value) -> Result<WriteOutcome, String> {
    let lab = lab.inner().clone();
    tauri::async_runtime::spawn_blocking(move || lab.write(code, value)).await.map_err(|e| e.to_string())
}

#[tauri::command]
#[specta::specta]
fn lab_pin(lab: LabState<'_>, codes: Vec<u16>) {
    lab.pin(codes)
}

#[tauri::command]
#[specta::specta]
fn lab_keep_awake(lab: LabState<'_>, on: bool) {
    lab.keep_awake(on)
}

#[tauri::command]
#[specta::specta]
fn lab_connect(lab: LabState<'_>, on: bool) {
    lab.connect(on)
}

#[tauri::command]
#[specta::specta]
async fn lab_export(lab: LabState<'_>) -> Result<String, String> {
    let lab = lab.inner().clone();
    tauri::async_runtime::spawn_blocking(move || lab.export()).await.map_err(|e| e.to_string())?
}

#[tauri::command]
#[specta::specta]
fn lab_label(lab: LabState<'_>, patch: LabelPatch) -> Result<Catalog, String> {
    lab.label(patch)
}

#[tauri::command]
#[specta::specta]
fn lab_note(lab: LabState<'_>, group: Option<u32>, text: String) {
    lab.note(group, text)
}

#[tauri::command]
#[specta::specta]
fn lab_fake(lab: LabState<'_>, action: FakeAction) -> Result<(), String> {
    lab.fake(action)
}

/// Parses pasted recipe text into slot settings, notes and per-field warnings.
#[tauri::command]
#[specta::specta]
fn recipe_parse(text: String) -> recipes::Parsed {
    recipes::parse_text(&text)
}

pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new()
        .commands(tauri_specta::collect_commands![
            lab_snapshot,
            lab_write,
            lab_pin,
            lab_keep_awake,
            lab_connect,
            lab_export,
            lab_label,
            lab_note,
            lab_fake,
            recipe_parse,
        ])
        // The bundled catalogue's shape; the window imports the JSON itself.
        .typ::<recipes::catalogue::Catalogue>()
        .events(tauri_specta::collect_events![lab::LabStatus, lab::LabProps, lab::LabChanges, lab::CatalogChanged])
        // Wall-clock ms and codes fit a JS number.
        .dangerously_cast_bigints_to_number()
}

pub fn bindings_language() -> specta_typescript::Typescript {
    specta_typescript::Typescript::default()
        .header("// Generated by tauri-specta from src-tauri/src/lib.rs (ukiyo_lib::specta_builder).\n// Do not edit. Regenerate: UKIYO_UPDATE_BINDINGS=1 cargo test bindings\n")
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let specta = specta_builder();
    #[cfg(debug_assertions)]
    {
        let out = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../app/src/bindings.ts");
        if let Err(e) = specta.export(bindings_language(), &out) {
            eprintln!("ukiyo: bindings.ts not written: {e}");
        }
    }
    let typed = specta.invoke_handler();
    let app = tauri::Builder::default()
        .invoke_handler(typed)
        .setup(move |app| {
            specta.mount_events(app);
            let data_dir = app.path().app_data_dir()?;
            std::fs::create_dir_all(&data_dir)?;
            let catalog_dir = lab::catalog_dir(&data_dir, app.path().resource_dir().ok());
            let handle = app.handle().clone();
            let lab = Lab::start(data_dir, catalog_dir, move |e| {
                let _ = match e {
                    LabEvent::Status(x) => x.emit(&handle),
                    LabEvent::Props(x) => x.emit(&handle),
                    LabEvent::Changes(x) => x.emit(&handle),
                    LabEvent::Catalog(x) => x.emit(&handle),
                };
            });
            app.manage(lab);
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("ukiyo starts");
    app.run(|handle, event| {
        if let tauri::RunEvent::ExitRequested { .. } = event {
            if let Some(lab) = handle.try_state::<Arc<Lab>>() {
                lab.shutdown();
            }
        }
    });
}

#[cfg(test)]
mod tests {
    #[test]
    fn bindings() {
        let dir = tempfile::tempdir().unwrap();
        let out = dir.path().join("bindings.ts");
        super::specta_builder().export(super::bindings_language(), &out).unwrap();
        let fresh = std::fs::read_to_string(out).unwrap();
        let committed = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../app/src/bindings.ts");
        if std::env::var_os("UKIYO_UPDATE_BINDINGS").is_some() {
            std::fs::write(&committed, &fresh).unwrap();
            return;
        }
        let on_disk = std::fs::read_to_string(&committed).unwrap_or_default();
        assert!(on_disk == fresh, "app/src/bindings.ts is out of date: UKIYO_UPDATE_BINDINGS=1 cargo test bindings");
    }
}
